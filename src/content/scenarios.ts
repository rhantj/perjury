/**
 * 사건 시나리오. 세계관은 경성 하나로 고정이고 사건만 바뀐다.
 *
 * 용의자 «이름» 6개는 시나리오와 무관하게 고정이다 (engine/cards.ts).
 * 여기서 바뀌는 것은 직함·수단·장소뿐이라 폴백 대사 풀을 한 벌로 유지할 수 있다.
 * 결정 근거는 docs/decisions/002-직업-풀과-시나리오.md.
 */

export interface Title {
  ko: string
  hanja: string
  /** 누구이고 그 자리에 왜 있었나. 한 문장. */
  who: string
  /**
   * 수상한 점. **여섯 명 모두에게 있어야 한다.**
   * 범인은 시드로 정해지므로(engine/setup.ts) 한 명만 유독 수상하게 쓰면 글이 판을 배신한다.
   * 여섯 다 동기와 빈 시간이 있어야 밀담에 거래 재료가 생긴다.
   */
  doubt: string
}

export interface Scenario {
  id: string
  /** 사건 이름. 랜딩 부제로 쓴다. */
  title: string
  hanja: string
  /** 한 문장 도입. 랜딩에서 한 글자씩 찍힌다. */
  intro: string
  /**
   * 착석 직후 게임판 위에 얹히는 세 문장.
   *
   * **여기서 단서를 주면 안 된다.** 설계 §1.3이 «제안/반증이 정보 획득의 유일한 공식 경로»라고
   * 못 박고 있어서, 현장 묘사가 카드를 지워 주는 순간 추리 구조가 무너진다. 분위기만 맡는다.
   */
  opening: readonly [string, string, string]
  /** 용의자 6명의 직함. cardsOfKind('suspect') 순서와 1:1로 맞춘다. */
  titles: readonly [Title, Title, Title, Title, Title, Title]
  /** 수단 4장. 코드상 kind는 'weapon'이지만 살인사건이 아닌 판도 있어 «수단»으로 읽는다. */
  means: readonly [string, string, string, string]
  /**
   * 제안 한 문장을 맺는 말. 「〈범인〉이 〈장소〉에서 〈수단〉으로 __」의 빈칸이다.
   *
   * 시나리오가 들고 있는 이유는 사건마다 «무엇을 했는가»가 다르기 때문이다 —
   * 밀고자 색출에서는 아무도 죽지 않았다. 화면에 「죽였습니다」를 박아 두면
   * 그 판에서 글이 판을 배신한다.
   */
  deed: string
  places: readonly [string, string, string, string, string]
}

