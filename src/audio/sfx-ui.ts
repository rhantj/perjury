/**
 * 화면 조작음 다섯. 버튼을 눌렀다는 «손끝의 반응»이지 판에서 벌어진 사건이 아니다.
 *
 * **게임 효과음과 같은 자리에서 겨루면 안 된다.** 제안(도장)·반증(카드)은 «무슨 일이
 * 일어났는가»를 알리는 소리라 길고 두껍다. 여기 다섯은 그 위에 얹히는 것이므로,
 * 셋을 통째로 다르게 잡아 아예 다른 층에 둔다.
 *
 *   **짧다** — 전부 0.1초 안에 끝난다. 열두 종 중 가장 짧은 반증(0.35초)의 3분의 1이다.
 *   **높다** — 0.8k~4.5k. 저역을 한 톨도 쓰지 않아 도장·퇴출과 주파수에서 안 겹친다.
 *   **작다** — 가장 큰 것이 0.11이다. 게임 소리의 5분의 1쯤이라 «들리는데 방해는 안 되는» 자리.
 *
 * 조작음이 커지면 판이 «기계»가 된다. 여기 값을 올리고 싶어지면 대개 게임 소리가
 * 작은 것이지 조작음이 작은 게 아니다.
 *
 * 다섯이 서로 갈리는 축은 **방향**이다. 진행은 올라가고, 취소는 내려가고,
 * 기본은 제자리다. 토글만 둘로 갈라 «켰다»와 «껐다»가 서로 반대로 움직인다.
 */

import { burst, tone } from './engine'
import { vary } from './voices'

/**
 * 톡. 따로 지정하지 않은 모든 버튼이 이것을 낸다.
 *
 * 판에서 가장 많이 나는 소리가 되므로 **가장 단순해야 한다** — 겹이 둘뿐이고
 * 음정이 거의 움직이지 않는다. 여기에 무엇이든 하나 더 얹으면 수십 번 듣는 동안 피로해진다.
 */
export function uiTap(at: number): void {
  burst(at, {
    gain: 0.09,
    attack: 0.0006,
    decay: 0.014,
    filter: 'bandpass',
    frequency: vary(2600, 60),
    q: 1.8,
  })
  /* 손톱이 아니라 «나무를 톡» 치는 쪽으로 붙드는 겹. 이게 없으면 소리가 유리가 된다. */
  tone(at, {
    type: 'triangle',
    from: vary(1240, 40),
    to: 980,
    gain: 0.06,
    attack: 0.001,
    decay: 0.045,
    fm: { ratio: 2.41, index: 320 },
  })
}

/**
 * 틱-. 진행·확정. 게임 시작, 브리핑 입장처럼 **화면이 넘어가는** 자리.
 *
 * 올라간다. 지목(challenge)도 올라가지만 그쪽은 0.6초에 걸쳐 400→2000을 쓸어 올리는
 * 사건이고, 이건 0.06초짜리 손끝이라 «같은 방향, 다른 층»이 된다.
 */
export function uiConfirm(at: number): void {
  burst(at, {
    gain: 0.1,
    attack: 0.0006,
    decay: 0.012,
    filter: 'bandpass',
    frequency: vary(3200, 60),
    q: 2,
  })
  tone(at, {
    type: 'triangle',
    from: 1568,
    to: 2093,
    gain: 0.09,
    attack: 0.001,
    decay: 0.055,
    fm: { ratio: 2.01, index: 240 },
    pan: -0.12,
  })
  /* 도착점에 짧게 하나 더. 두 번째가 있어야 «넘어갔다»가 되고, 없으면 그냥 «눌렸다»다. */
  tone(at, {
    type: 'sine',
    from: 2349,
    gain: 0.05,
    attack: 0.001,
    decay: 0.05,
    delay: 0.035,
    pan: 0.18,
  })
}

/**
 * 특. 취소·뒤로·닫기.
 *
 * 확정을 그대로 뒤집는다 — 내려가고, 두 번째 음이 없다. **끝을 맺지 않는 것**이
 * «되돌아왔다»를 만든다. 도착점을 주면 그건 취소가 아니라 또 하나의 확정이 된다.
 */
export function uiBack(at: number): void {
  burst(at, {
    gain: 0.08,
    attack: 0.0008,
    decay: 0.016,
    filter: 'bandpass',
    frequency: vary(1800, 60),
    q: 1.4,
  })
  tone(at, {
    type: 'triangle',
    from: 1244,
    to: 784,
    gain: 0.085,
    attack: 0.0015,
    decay: 0.07,
    fm: { ratio: 1.72, index: 180 },
    pan: 0.12,
  })
}

/**
 * 툭. 둔탁한 쪽. 지금은 **시나리오 카드**가 쓴다(`data-sfx="heavy"`).
 *
 * 「톡」이 손톱으로 치는 소리라면 이건 **두꺼운 조서 뭉치를 손바닥으로 짚는** 소리다.
 * 둔탁함은 소리를 키워서 나오지 않는다 — **고역을 걷어내야** 나온다. 그래서 위 넷과 달리
 * 밴드패스가 아니라 로패스를 쓰고, 위에 얹는 밝은 겹이 하나도 없다. 뭘 더 얹는 순간 «맑아진다».
 *
 * 여기만 저역을 쓴다. 다른 넷의 «0.8k 아래를 안 쓴다» 원칙을 깨는 건데, 이 소리가
 * 나는 자리(시나리오 고르기)는 **판이 시작되기 전**이라 도장·퇴출과 겹칠 일이 없어서다.
 * 판 안의 버튼에 이걸 달면 그때는 겹친다.
 *
 * ---
 *
 * **첫 판본은 «안 들린다»는 말을 들었다. 크기 문제가 아니라 음역 문제였다.**
 *
 * 무게를 68~90Hz에 뒀는데 노트북 스피커는 그 대역을 사실상 내보내지 못한다.
 * 계기로 재면 분명히 울리는데 스피커에서는 아무 일도 안 일어나는 것이다.
 * 게인을 올려봐야 «안 나오는 대역이 조금 더 세게 안 나올» 뿐이다.
 *
 * 그래서 무게를 **150~600Hz로 끌어올렸다.** 작은 스피커도 이 대역은 낸다.
 * 둔탁함은 저역이 아니라 **고역이 없는 것**에서 나오므로, 음역을 올려도 위를 계속
 * 비워 두면 둔탁한 채로 남는다. 여기서 2k 위를 하나라도 얹으면 그 순간 「톡」이 된다.
 */
export function uiHeavy(at: number): void {
  /* 조서 뭉치가 눌리는 «퍽». 로패스라 위가 없고, decay가 길어 «탁»이 아니라 «툭»이 된다. */
  burst(at, {
    gain: 0.34,
    attack: 0.001,
    decay: 0.06,
    filter: 'lowpass',
    frequency: vary(620, 50),
    q: 0.7,
  })
  /* 손바닥이 닿는 자리. 여기가 «들리는» 몫을 거의 다 낸다 — 작은 스피커가 내는 가장 낮은 대역이다. */
  burst(at, {
    gain: 0.26,
    attack: 0.0015,
    decay: 0.045,
    filter: 'bandpass',
    frequency: vary(440, 40),
    q: 1.1,
    pan: 0.08,
  })
  /* 무게. 음정이 잡히면 북이 되므로 165에서 곧장 110으로 주저앉힌다 — 머무는 자리가 없어야 한다. */
  tone(at, {
    type: 'sine',
    from: 165,
    to: 110,
    gain: 0.3,
    attack: 0.002,
    decay: 0.11,
  })
  /* 나무 책상이 대답하는 몫. FM 비를 정수에서 떼어 놔야 «통»이 아니라 «판»으로 들린다. */
  tone(at, {
    type: 'triangle',
    from: vary(330, 12),
    to: 240,
    gain: 0.16,
    attack: 0.002,
    decay: 0.08,
    fm: { ratio: 1.87, index: 90 },
    pan: 0.1,
  })
}

/**
 * 스륵. 종이 한 장이 스치는 소리. **카드 위에 커서가 올라올 때마다** 난다.
 *
 * 종이는 **음정이 없다.** 그래서 오실레이터를 하나도 쓰지 않고 잡음만 쓴다.
 * 알갱이 셋으로 나눈 것은 종이가 «한 번에» 스치지 않기 때문이다 — 붙여 놓으면
 * 스치는 소리가 아니라 «칙» 하는 잡음 한 방이 된다.
 *
 * **처음엔 「톡」의 절반쯤으로 잡았다가 «안 들린다»고 해서 2.4배로 올렸다.**
 * 호버는 클릭보다 훨씬 자주 나므로 원래는 물러나 있는 게 맞지만, 물러나다 못해
 * 없는 것이 되면 그건 그냥 없는 기능이다. 지금은 「톡」보다 조금 크다.
 *
 * 이 대역(2.1k~4.3k)은 작은 스피커가 가장 잘 내는 자리라 **게인을 올린 만큼 그대로
 * 들린다** — 시나리오 클릭음이 저역이라 게인을 올려도 안 들렸던 것과 반대다.
 * 성가시면 여기 셋을 같은 비율로 내리면 된다. 비율을 깨면 종이가 아니게 된다.
 */
export function uiPaper(at: number): void {
  const grains = [
    { delay: 0, hz: 3200, gain: 0.13, pan: -0.1 },
    { delay: 0.012, hz: 2100, gain: 0.095, pan: 0.14 },
    { delay: 0.026, hz: 4300, gain: 0.066, pan: 0.02 },
  ]
  for (const g of grains) {
    burst(at, {
      gain: g.gain,
      attack: 0.001,
      decay: 0.022,
      filter: 'bandpass',
      /* 매번 흔들어야 한다. 같은 자리에서 나면 종이가 아니라 기계음으로 굳는다. */
      frequency: vary(g.hz, 260),
      q: 1.1,
      delay: g.delay,
      pan: g.pan,
    })
  }
}

/**
 * 딸깍(켬). 스위치가 걸리는 쪽.
 *
 * 토글만 둘로 나눈 이유는, 켜고 끄는 데 같은 소리가 나면 **지금 어느 쪽이 됐는지
 * 소리로는 알 수 없기** 때문이다. 음소거 버튼이 특히 그렇다 — 끈 다음에는 확인할 소리가
 * 아예 없으므로, 끄는 그 순간의 소리가 유일한 단서다.
 */
export function uiToggleOn(at: number): void {
  burst(at, {
    gain: 0.11,
    attack: 0.0005,
    decay: 0.01,
    filter: 'bandpass',
    frequency: vary(4200, 50),
    q: 2.6,
  })
  tone(at, {
    type: 'square',
    from: 1760,
    gain: 0.05,
    attack: 0.0008,
    decay: 0.03,
    fm: { ratio: 2.76, index: 200 },
  })
}

/** 딸깍(끔). 켬을 한 옥타브 아래에서, 조금 더 무디게. */
export function uiToggleOff(at: number): void {
  burst(at, {
    gain: 0.1,
    attack: 0.0007,
    decay: 0.014,
    filter: 'bandpass',
    frequency: vary(2100, 50),
    q: 2.2,
  })
  tone(at, {
    type: 'square',
    from: 880,
    gain: 0.045,
    attack: 0.001,
    decay: 0.04,
    fm: { ratio: 2.76, index: 140 },
  })
}
